func TestParseStaysStrict(t *testing.T) {
	for _, in := range []string{"около 1850", "12 марта 1850", "1900 жылға дейін", "между 1850 и 1860", "шамамен 1850"} {
		if d, err := Parse(in); err == nil {
			t.Errorf("Parse(%q) accepted as %q", in, d.String())
		}
	}
}
